"""Figure F: the four performance curves and the 40-feature importance ranking.

Both read only from `results/exp_f_*.json|csv`, generated by
`experiments/exp_curves.py`. Nothing is hand-entered.
"""
from __future__ import annotations

import json

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from _audit import common as C

W, DPI = 3.5, 300
plt.rcParams.update({
    'font.size': 6.5, 'axes.titlesize': 7, 'axes.labelsize': 6.5,
    'legend.fontsize': 5, 'xtick.labelsize': 5.5, 'ytick.labelsize': 5.5,
    'font.family': 'serif', 'pdf.fonttype': 42, 'axes.linewidth': 0.6,
    'lines.linewidth': 0.9,
})
FIG = C.FIGURES
(FIG / 'png').mkdir(exist_ok=True)


def fig_curves():
    d = json.loads((C.RESULTS / 'exp_f_curves.json').read_text(encoding='utf-8'))
    fig, ax = plt.subplots(2, 2, figsize=(W * 1.62, 4.3))

    r = d['roc']
    ax[0, 0].plot(r['fpr'], r['tpr'], color='#1f4e79', lw=1.0,
                  label=f"AUC = {d['auc']:.3f}")
    ax[0, 0].plot([0, 1], [0, 1], 'k:', lw=0.5)
    ax[0, 0].set_xlabel('false positive rate')
    ax[0, 0].set_ylabel('true positive rate')
    ax[0, 0].set_title('(a) ROC')
    ax[0, 0].legend(frameon=False, loc='lower right')

    p = d['pr']
    ax[0, 1].plot(p['recall'], p['precision'], color='#c00000', lw=1.0,
                  label=f"AP = {d['average_precision']:.3f}")
    ax[0, 1].axhline(d['n'] and 0.5, color='k', ls=':', lw=0.5)
    ax[0, 1].set_xlabel('recall')
    ax[0, 1].set_ylabel('precision')
    ax[0, 1].set_title('(b) Precision-recall')
    ax[0, 1].legend(frameon=False, loc='lower left')

    c = d['calibration']
    ax[1, 0].plot(c['mean_predicted'], c['fraction_positive'], 'o-',
                  color='#548235', lw=0.9, ms=2.5, label='ensemble')
    ax[1, 0].plot([0, 1], [0, 1], 'k:', lw=0.5, label='perfect')
    ax[1, 0].set_xlabel('mean predicted probability')
    ax[1, 0].set_ylabel('observed fraction positive')
    ax[1, 0].set_title(f"(c) Calibration (Brier {d['brier']:.3f})")
    ax[1, 0].legend(frameon=False, loc='upper left')

    dc = d['decision_curve']
    t = [x['threshold'] for x in dc]
    ax[1, 1].plot(t, [x['net_benefit'] for x in dc], color='#1f4e79',
                  lw=1.1, label='ensemble')
    ax[1, 1].plot(t, [x['treat_all'] for x in dc], color='#7f6000',
                  lw=0.8, ls='--', label='treat all')
    ax[1, 1].axhline(0, color='k', lw=0.8, ls='-', label='treat none')
    ax[1, 1].set_xlabel('threshold probability')
    ax[1, 1].set_ylabel('net benefit')
    ax[1, 1].set_title('(d) Decision curve')
    ax[1, 1].legend(frameon=False, loc='upper right')

    fig.tight_layout(pad=0.35)
    fig.savefig(FIG / 'fig7_curves.pdf', dpi=DPI, bbox_inches='tight')
    fig.savefig(FIG / 'png' / 'fig7_curves.png', dpi=150, bbox_inches='tight')
    plt.close(fig)
    print("  fig7_curves.pdf")


def fig_importance():
    d = pd.read_csv(C.RESULTS / 'exp_f_importance.csv')
    d = d.sort_values('importance')
    fig, ax = plt.subplots(figsize=(W * 1.15, 4.6))
    ax.barh(d['feature'], d['importance'], color='#1f4e79', height=0.72)
    ax.set_xlabel('mean normalised importance over 40 splits')
    ax.set_title('GBM feature importance, all 40 selected features', fontsize=7)
    ax.tick_params(axis='y', labelsize=4.6)
    for y, (v, lab) in enumerate(zip(d['importance'], d['label'])):
        ax.text(v + 0.002, y, lab, va='center', fontsize=4.0, color='#555')
    fig.tight_layout(pad=0.3)
    fig.savefig(FIG / 'fig8_importance.pdf', dpi=DPI, bbox_inches='tight')
    fig.savefig(FIG / 'png' / 'fig8_importance.png', dpi=150, bbox_inches='tight')
    plt.close(fig)
    print("  fig8_importance.pdf")


if __name__ == '__main__':
    fig_curves()
    fig_importance()
